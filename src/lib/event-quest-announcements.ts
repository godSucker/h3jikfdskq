/**
 * Карточка задания пуста, если цепочки больше нет в данных или ни одного из
 * добавленных этапов в ней не осталось. Новая цепочка без addedStepIds пуста
 * только если у неё нет этапов.
 */
export function isEmptyQuestItem(
  item: { addedStepIds?: string[] },
  chainStepIds: Set<string> | undefined,
): boolean {
  if (!chainStepIds || chainStepIds.size === 0) return true
  if (!item.addedStepIds?.length) return false
  return !item.addedStepIds.some((id) => chainStepIds.has(id))
}

