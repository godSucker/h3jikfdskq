// Отпечаток содержимого доски бинго: по нему решается, пора ли
// перерендерить статичный скриншот доски (scripts/render-bingo-screenshots.ts).
//
// Считается в двух местах из одних и тех же данных bingos.json: на странице
// /bingo (атрибут data-bingo-hash у панели доски) и в скрипте рендера. Скрипт
// рендерит доску, только когда живая страница уже отдаёт тот же отпечаток,
// что и репозиторий, - иначе на скриншот попала бы версия доски из прошлого
// деплоя, а записана была бы как свежая.
//
// Хэш не криптографический (cyrb53): нужен только для сравнения версий и
// должен одинаково считаться и в Node, и в сборке Astro без node:crypto.

// Поднять, если поменялась вёрстка доски и все сохранённые скриншоты надо
// перерендерить.
const RENDER_VERSION = 1

export function bingoBoardHash(board: unknown): string {
  const str = `v${RENDER_VERSION}:${JSON.stringify(board) ?? ''}`
  let h1 = 0xdeadbeef
  let h2 = 0x41c6ce57
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i)
    h1 = Math.imul(h1 ^ ch, 2654435761)
    h2 = Math.imul(h2 ^ ch, 1597334677)
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909)
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909)
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(36)
}
