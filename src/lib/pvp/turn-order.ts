import type { CombatUnit } from './battle-profile'

/** Обратный перевод CombatUnit.speedX100 (сайтовая конвенция, больше=быстрее) в
 *  игровую сырую (меньше=быстрее) - см. заголовок файла. */
function gameNativeSpeed(u: CombatUnit): number {
  return 1000 / u.speedX100
}

/** Fisher-Yates только внутри групп с одинаковым tick (не трогает порядок между группами). */
function shuffleTies(
  candidates: { unit: CombatUnit; tick: number }[],
  rng: () => number,
): void {
  let i = 0
  while (i < candidates.length) {
    let j = i + 1
    while (j < candidates.length && candidates[j].tick === candidates[i].tick) j += 1
    for (let k = j - 1; k > i; k -= 1) {
      const r = i + Math.floor(rng() * (k - i + 1))
      ;[candidates[k], candidates[r]] = [candidates[r], candidates[k]]
    }
    i = j
  }
}

export function computeTurnQueue(
  units: CombatUnit[],
  turnsNeeded: number,
  rng: () => number = Math.random,
): CombatUnit[] {
  const living = units.filter((u) => u.isAlive && u.speedX100 > 0)
  if (living.length === 0) return []

  // orderBySpeed сортирует по возрастанию game-native (меньше=быстрее) - опорный
  // юнит для порога это ПЕРВЫЙ элемент = БЫСТРЕЙШИЙ.
  const fastestRef = Math.min(...living.map(gameNativeSpeed))
  const queue: CombatUnit[] = []

  let round = 0
  // Защита от бесконечного цикла (не должна сработать при живых юнитах и fastestRef>0)
  const roundCap = turnsNeeded * living.length + 1000

  while (queue.length < turnsNeeded && round < roundCap) {
    const lowThreshold = fastestRef * (round + 1)
    const highThreshold = fastestRef * (round + 2)

    const candidates: { unit: CombatUnit; tick: number }[] = []
    for (const unit of living) {
      const s = gameNativeSpeed(unit)
      const n = Math.ceil(lowThreshold / s)
      const tick = n * s
      if (tick < highThreshold) candidates.push({ unit, tick })
    }
    candidates.sort((a, b) => a.tick - b.tick)
    shuffleTies(candidates, rng)

    for (const { unit } of candidates) {
      if (queue.length >= turnsNeeded) break
      // isDead-проверка "на лету" (как в игре) - юнит мог умереть до своего хода
      // внутри уже сформированной очереди; сама очередь строится по живым на старте,
      // а фактический пропуск мёртвых - забота вызывающего кода (fight-engine),
      // который идёт по очереди и скипает тех, кто умер раньше своего хода.
      queue.push(unit)
    }
    round += 1
  }

  return queue
}
